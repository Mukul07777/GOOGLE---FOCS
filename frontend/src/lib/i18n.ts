export function translate(text: string, language: UiLanguage | string | null | undefined): string {
  const row = STRINGS[text];
  if (!row || !language || language === "en") return text;
  return language === "hi" ? row[0] : language === "hinglish" ? row[1] : text;
}

/** `t("Live lecture")` in the signed-in student's language. */
export function useT(): (text: string) => string {
  const language = useAuth((s) => s.user?.language) ?? "en";
  return (text: string) => translate(text, language);
}

